"""Synthesize eval audio with Bulbul: one voice per role, turns concatenated, optional noise and fast speech.
ALL OUTPUT IS SYNTHETIC speech, not real clinic audio. Run from repo root:
  python eval/synthesize_audio.py            # prints the API-call estimate and stops
  python eval/synthesize_audio.py --yes      # synthesizes (skips clips that already exist)"""
import array
import json
import math
import random
import sys
import wave
import io
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'backend'))

import config
import sarvam_client
import voice

OUT = ROOT / 'eval' / 'audio'
SNR_DB = 10          # noisy clips: speech-to-noise ratio
FAST_PACE = 1.4      # fast clips: Bulbul pace option
GAP_S = 0.4


def load(path=None):
    path = Path(path or config.EVAL_SCENARIO_FILE)
    path = path if path.is_absolute() else ROOT / path
    return [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines() if line.strip()]


def estimate(scenarios):
    tts_calls = sum(len(s['turns']) for s in scenarios)
    n = len(scenarios)
    return {'scenarios': n, 'bulbul_tts_calls': tts_calls, 'per_eval_run_stt_calls': n,
            'per_eval_run_llm_calls': n, 'per_eval_run_diarization_batch_jobs_if_enabled': n}


def add_noise(wav_bytes, snr_db=SNR_DB, seed=0):
    """Mix Gaussian noise at the given signal-to-noise ratio (pure Python, deterministic)."""
    with wave.open(io.BytesIO(wav_bytes)) as r:
        params, frames = r.getparams(), r.readframes(r.getnframes())
    samples = array.array('h')
    samples.frombytes(frames)
    rms = math.sqrt(sum(x * x for x in samples) / max(len(samples), 1))
    sigma = rms / (10 ** (snr_db / 20))
    rng = random.Random(seed)
    noisy = array.array('h', (max(-32768, min(32767, int(x + rng.gauss(0, sigma)))) for x in samples))
    out = io.BytesIO()
    with wave.open(out, 'wb') as w:
        w.setparams(params)
        w.writeframes(noisy.tobytes())
    return out.getvalue()


def silence(like, seconds=GAP_S):
    with wave.open(io.BytesIO(like)) as r:
        p = r.getparams()
    out = io.BytesIO()
    with wave.open(out, 'wb') as w:
        w.setparams(p)
        w.writeframes(b'\x00' * (int(p.framerate * seconds) * p.nchannels * p.sampwidth))
    return out.getvalue()


def synthesize(sc):
    options = {'pace': FAST_PACE} if 'fast' in sc['tags'] else {}
    parts = []
    for turn in sc['turns']:
        role = 'clinician' if turn['speaker'] == 'clinician' else 'patient'
        parts.append(sarvam_client.tts(turn['text'], sc['language'], speaker=sc['voices'][role], **options))
    spaced = []
    for p in parts:
        spaced += [p, silence(p)]
    wav = voice.join_wavs(spaced[:-1])
    return add_noise(wav) if 'noisy' in sc['tags'] else wav


if __name__ == '__main__':
    scenarios = load()
    print('Estimated API usage:', json.dumps(estimate(scenarios), indent=2))
    if '--yes' not in sys.argv:
        sys.exit('Nothing synthesized. Re-run with --yes to spend the Bulbul calls above.')
    config.MOCK_MODE = False
    OUT.mkdir(parents=True, exist_ok=True)
    for sc in scenarios:
        path = OUT / f"{sc['id']}.wav"
        if path.exists():
            continue
        path.write_bytes(synthesize(sc))
        print('wrote', path.relative_to(ROOT))
    (OUT / 'README.txt').write_text('SYNTHETIC audio generated by eval/synthesize_audio.py with Bulbul. Not real clinic audio.\n')
